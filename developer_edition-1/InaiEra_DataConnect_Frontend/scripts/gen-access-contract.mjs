#!/usr/bin/env node
/*
 * Generates src/types/permissions.generated.ts — the typed list of DataConnect permission IDs — from the backend's
 * permissions.json (InaiEra_DataConnect_Backend, repo root; contract docs/auth/01-CONTRACT.md section 7), so the UI
 * can only check IDs the backend actually declares. WHO holds which permission is decided by roles in the Admin
 * Portal; nothing here knows about roles.
 *
 *   npm run gen:access-contract          rewrite the file from permissions.json
 *   npm run check:access-contract        fail (exit 1) if the committed file differs — for CI and before a release
 *
 * DATACONNECT_PERMISSIONS_FILE   path to permissions.json (default: ../InaiEra_DataConnect_Backend/permissions.json)
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const SOURCE = resolve(process.env.DATACONNECT_PERMISSIONS_FILE || join(ROOT, "..", "InaiEra_DataConnect_Backend", "permissions.json"));
const OUT = join(ROOT, "src", "types", "permissions.generated.ts");
const check = process.argv.includes("--check");

function validate(catalog) {
  const fail = (why) => { console.error(`${SOURCE} is not a valid permissions.json: ${why}`); process.exit(2); };
  if (!catalog || catalog.app !== "dataconnect" || !Array.isArray(catalog.permissions)) fail('expected { app: "dataconnect", permissions: [...] }');
  const ids = catalog.permissions.map((p) => p && p.id);
  for (const id of ids) {
    if (typeof id !== "string" || !/^dataconnect:[a-z][a-z-]*:[a-z][a-z-]*$/.test(id)) fail(`permission id ${JSON.stringify(id)} is not dataconnect:<area>:<action>`);
  }
  if (new Set(ids).size !== ids.length) fail("duplicate permission ids");
  if (!ids.includes("dataconnect:access:view")) fail("dataconnect:access:view is missing");
}

function render(catalog) {
  const rows = catalog.permissions.map((p) => `  ${JSON.stringify(p.id)},`).join("\n");
  return `/*
 * GENERATED by scripts/gen-access-contract.mjs from the backend's permissions.json — do not edit by hand.
 * Regenerate with \`npm run gen:access-contract\`; \`npm run check:access-contract\` fails when this file has drifted.
 */
export const PERMISSION_IDS = [
${rows}
] as const;
`;
}

let catalog;
try {
  catalog = JSON.parse(readFileSync(SOURCE, "utf8"));
} catch (e) {
  console.error(`Could not read ${SOURCE}: ${e instanceof Error ? e.message : e}\nSet DATACONNECT_PERMISSIONS_FILE to the backend's permissions.json.`);
  process.exit(2);
}
validate(catalog);
const next = render(catalog);

if (check) {
  let current = "";
  try { current = readFileSync(OUT, "utf8"); } catch { /* missing counts as drift */ }
  if (current !== next) {
    console.error("src/types/permissions.generated.ts differs from the backend's permissions.json. Run `npm run gen:access-contract` and review the change.");
    process.exit(1);
  }
  console.log("permission list is up to date with the backend");
} else {
  writeFileSync(OUT, next);
  console.log(`wrote ${OUT} (${catalog.permissions.length} permissions)`);
}
