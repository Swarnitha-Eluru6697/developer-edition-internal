// Generates src/rbac/generated/permissions.ts from the Workspace permission list.
//
//   node scripts/generate-rbac.mjs            write the file
//   node scripts/generate-rbac.mjs --check    exit 1 if the file is stale (CI / vitest drift test)
//
// openapi/permissions.json is a copy of Pralai_workspace_backend/permissions.json — the one place the Workspace permission IDs
// are declared (platform permission contract, section 7). Who holds which permission is data owned by the Admin Portal; nothing
// in this repo maps people or groups to permissions.
import { readFileSync, writeFileSync, existsSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const SRC = resolve(root, "openapi/permissions.json");
const OUT = resolve(root, "src/rbac/generated/permissions.ts");

const ID = /^workspace:[a-z]+(-[a-z]+)*:[a-z]+(-[a-z]+)*$/;

/** Throws if `doc` is not a valid Workspace permissions.json. */
export function validate(doc) {
  if (!doc || doc.app !== "workspace" || !Array.isArray(doc.permissions)) throw new Error("not the workspace permissions.json");
  const seen = new Set();
  for (const p of doc.permissions) {
    if (typeof p.id !== "string" || !ID.test(p.id)) throw new Error(`bad permission id ${JSON.stringify(p.id)}`);
    if (seen.has(p.id)) throw new Error(`duplicate permission id ${p.id}`);
    if (typeof p.label !== "string" || !p.label) throw new Error(`permission ${p.id} has no label`);
    seen.add(p.id);
  }
  if (!seen.has("workspace:access:view")) throw new Error("workspace:access:view is missing");
}

export function render(doc) {
  validate(doc);
  const q = (s) => JSON.stringify(s);
  const lines = [
    "// GENERATED by scripts/generate-rbac.mjs from openapi/permissions.json. DO NOT EDIT.",
    "// Change permissions.json in the workspace backend, copy it to openapi/permissions.json, then run `npm run codegen:rbac`.",
    "",
    `export const PERMISSIONS_VERSION = ${doc.version} as const;`,
    "",
    "/** Every Workspace permission ID, in permissions.json order. */",
    "export const PERMISSIONS = [",
    ...doc.permissions.map((p) => `  ${q(p.id)},`),
    "] as const;",
    "export type Permission = (typeof PERMISSIONS)[number];",
    "",
    "export const PERMISSION_LABELS: Record<Permission, string> = {",
    ...doc.permissions.map((p) => `  ${q(p.id)}: ${q(p.label)},`),
    "};",
    "",
    "export const PERMISSION_DESCRIPTIONS: Record<Permission, string> = {",
    ...doc.permissions.map((p) => `  ${q(p.id)}: ${q(p.description ?? "")},`),
    "};",
    "",
  ];
  return lines.join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  let text;
  try {
    text = render(JSON.parse(readFileSync(SRC, "utf8")));
  } catch (e) {
    console.error(`${SRC}: ${e.message}`); process.exit(2);
  }
  if (process.argv.includes("--check")) {
    if (!existsSync(OUT) || readFileSync(OUT, "utf8") !== text) {
      console.error(`${OUT} is stale: run \`npm run codegen:rbac\``); process.exit(1);
    }
  } else {
    mkdirSync(dirname(OUT), { recursive: true });
    writeFileSync(OUT, text);
  }
}
